"""Finova dashboard API (read-only over Route 2 artefacts).

The current contract is served as generated by ``run_route2``; other
country/year scopes are built on demand from the warehouse through the same
deterministic builders (no LLM). Generated scopes are kept in memory and in a
local cache directory so a second visit is immediate. ``POST /api/ask`` only
reuses numbers already present in the selected spec's facts.
"""
from __future__ import annotations

import json
import logging
import os
import threading
from pathlib import Path
from typing import Any, Callable, Mapping

import duckdb
from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from pydantic import ValidationError

from biflow.agents.analyst import AskRequest, answer_question, build_insights, build_xai
from biflow.config import ROOT, load_config, resolve
from biflow.tools.analysis import DEFAULT_KPIS, AnalysisRequest, AnalysisService
from biflow.tools.dashboard_spec import (
    DashboardSpec, PEERS, REFERENCE_PATH, build_finova_spec,
    load_pipeline_info, load_reference,
)
from biflow.tools.kpi import DEFAULT_CATALOG
from biflow.tools.warehouse_reader import WarehouseReader
from biflow.utils.io import load_json

SpecBuilder = Callable[[str, int], dict[str, Any]]


def _current_year(payload: Mapping[str, Any]) -> int:
    year = payload.get("year")
    if type(year) is not int:
        raise ValueError("spec year missing")
    return year


def _current_iso3(payload: Mapping[str, Any]) -> str:
    iso3 = (payload.get("country") or {}).get("iso3")
    if not isinstance(iso3, str) or not iso3:
        raise ValueError("spec country missing")
    return iso3


def _attach_analysis(payload: Mapping[str, Any], insights: Mapping[str, Any],
                     xai: Mapping[str, Any] | None) -> dict[str, Any]:
    data = dict(payload)
    data["pages"] = [dict(page) for page in payload.get("pages") or []]
    for page in data["pages"]:
        page["insights"] = [dict(item) for item in insights.get(page.get("id"), [])]
        if page.get("id") == "exclusion":
            if xai is not None:
                page["xai"] = dict(xai)
            else:
                page.pop("xai", None)
    return DashboardSpec.model_validate(data).model_dump(mode="json")


class WarehouseSpecBuilder:
    """Deterministic on-demand spec for a scope not covered by the public file."""

    def __init__(
        self, cfg: Mapping[str, Any], *, warehouse: Path, lineage: Path,
        quality: Path, reference: Path, reports: Path, history_dir: Path,
    ) -> None:
        self.cfg = cfg
        self.warehouse = warehouse
        self.lineage = lineage
        self.quality = quality
        self.reference = reference
        self.reports = reports
        self.history_dir = history_dir
        self._lock = threading.Lock()
        self._service: AnalysisService | None = None
        self._service_stamp = 0.0
        self._pipeline: tuple[float, dict[str, Any]] | None = None
        self._reference_catalog: tuple[float, Any] | None = None

    def _pipeline_for(self, reader: WarehouseReader, stamp: float) -> dict[str, Any]:
        if self._pipeline is None or self._pipeline[0] != stamp:
            history_files = sorted(
                [path for path in self.history_dir.glob("*.json")
                 if path.is_file()],
                key=lambda path: path.stat().st_mtime, reverse=True,
            )[:20]
            self._pipeline = (stamp, load_pipeline_info(
                self.cfg, reader=reader, lineage_path=self.lineage,
                quality_report_path=self.quality, reports_dir=self.reports,
                history_files=history_files,
            ))
        return self._pipeline[1]

    def _reference_for(self, stamp: float) -> Any:
        if self._reference_catalog is None or self._reference_catalog[0] != stamp:
            self._reference_catalog = (stamp, load_reference(self.reference))
        return self._reference_catalog[1]

    def __call__(self, iso3: str, year: int) -> dict[str, Any]:
        if not self.warehouse.is_file():
            raise FileNotFoundError(f"warehouse introuvable : {self.warehouse}")
        with self._lock:
            stamp = self.warehouse.stat().st_mtime
            if self._service is None or self._service_stamp != stamp:
                self._service = AnalysisService(
                    self.warehouse, DEFAULT_CATALOG, lineage_path=self.lineage,
                    quality_report_path=self.quality,
                )
                self._service_stamp = stamp
                self._pipeline = None
                self._reference_catalog = None
            request = AnalysisRequest(
                iso3=(iso3, *(code for code in PEERS if code != iso3)),
                kpi_ids=DEFAULT_KPIS, mode="year", year=year,
                series_iso3=(iso3,), include_trends=False,
                include_rankings=False, include_comparisons=False,
            )
            dataset = self._service.build(request)
            reader = WarehouseReader(self.warehouse)
            pipeline = self._pipeline_for(reader, stamp)
            reference = self._reference_for(stamp)
            spec = build_finova_spec(
                dataset, run_id=f"api_{iso3}_{year}", iso3=iso3, year=year,
                reader=reader, reference=reference, pipeline=pipeline,
            )
        facts = [fact.model_dump(mode="json") for fact in spec.facts]
        insights, _ = build_insights(facts, spec.country.name)
        xai, _ = build_xai(facts, spec.country.name)
        return _attach_analysis(
            spec.model_dump(mode="json"), insights, xai,
        )


def create_app(
    *,
    spec_path: str | Path | None = None,
    warehouse_path: str | Path | None = None,
    lineage_path: str | Path | None = None,
    quality_path: str | Path | None = None,
    reference_path: str | Path | None = None,
    reports_dir: str | Path | None = None,
    history_dir: str | Path | None = None,
    generated_dir: str | Path | None = None,
    web_dist: str | Path | None = None,
    spec_builder: SpecBuilder | None = None,
    prewarm: bool | None = None,
) -> FastAPI:
    cfg = load_config()
    dashboard = cfg.get("dashboard") or {}
    paths = cfg.get("paths") or {}
    spec_file = resolve(
        spec_path if spec_path is not None
        else dashboard.get("spec_output", "dashboard_app/public/data/finova.json")
    )
    warehouse = resolve(
        warehouse_path if warehouse_path is not None
        else Path(paths.get("processed", "data/processed")) / "warehouse.duckdb"
    )
    lineage = resolve(
        lineage_path if lineage_path is not None
        else warehouse.with_name("lineage.json")
    )
    quality = resolve(
        quality_path if quality_path is not None
        else Path(paths.get("quality", "data/quality")) / "quality_report.json"
    )
    reference = resolve(
        reference_path if reference_path is not None
        else dashboard.get("reference_path", REFERENCE_PATH)
    )
    reports = resolve(
        reports_dir if reports_dir is not None else paths.get("reports", "outputs/reports")
    )
    history = resolve(
        history_dir if history_dir is not None
        else dashboard.get("history_dir", "outputs/dashboard/history")
    )
    generated_root = resolve(
        generated_dir if generated_dir is not None
        else dashboard.get("generated_dir", "outputs/dashboard/generated")
    )
    dist = resolve(
        web_dist if web_dist is not None else "dashboard_app/web/dist"
    )
    builder = spec_builder or WarehouseSpecBuilder(
        cfg, warehouse=warehouse, lineage=lineage, quality=quality,
        reference=reference, reports=reports, history_dir=history,
    )
    persist = generated_root if spec_builder is None else None

    def _store_generated(path: Path, payload: Mapping[str, Any]) -> None:
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_suffix(path.suffix + ".tmp")
            with open(temporary, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, ensure_ascii=False, allow_nan=False)
            os.replace(temporary, path)
        except (OSError, ValueError):
            logging.getLogger(__name__).warning(
                "cache disque non écrit : %s", path, exc_info=True,
            )

    app = FastAPI(
        title="Finova Dashboard API",
        version="1.0.0",
        description="Contrat Route 2 en lecture seule, réponses chiffrées vérifiées.",
    )
    app.add_middleware(
        CORSMiddleware,
        allow_origins=[
            "http://127.0.0.1:5173", "http://localhost:5173",
        ],
        allow_methods=["GET", "POST"],
        allow_headers=["*"],
    )

    cache: dict[tuple[str, int], dict[str, Any]] = {}
    survey_cache: dict[tuple[str, float], list[int]] = {}
    lock = threading.Lock()

    def warehouse_stamp() -> float:
        try:
            return warehouse.stat().st_mtime
        except OSError:
            return 0.0

    def findex_years(iso3: str) -> list[int]:
        """Years with an actual Findex observation, so the UI can flag survey waves."""
        key = (iso3, warehouse_stamp())
        with lock:
            hit = survey_cache.get(key)
            if hit is not None:
                return hit
        years: list[int] = []
        if warehouse.is_file():
            try:
                with duckdb.connect(str(warehouse), read_only=True) as con:
                    years = [
                        int(row[0]) for row in con.execute(
                            "SELECT DISTINCT year FROM fact "
                            "WHERE source = 'findex' AND iso3 = ? AND value IS NOT NULL "
                            "ORDER BY year",
                            [iso3],
                        ).fetchall()
                    ]
            except duckdb.Error:
                years = []
        with lock:
            if len(survey_cache) >= 64:
                survey_cache.clear()
            survey_cache[key] = years
        return years

    def load_current() -> dict[str, Any]:
        try:
            payload = load_json(spec_file)
        except (OSError, ValueError) as exc:
            raise HTTPException(
                status_code=503,
                detail=f"contrat indisponible : {spec_file} ({type(exc).__name__})",
            ) from exc
        if not isinstance(payload, dict) or not payload.get("pages"):
            raise HTTPException(
                status_code=503,
                detail="contrat vide ou invalide : exécutez run_route2 d'abord",
            )
        return payload

    def generated(iso3: str, year: int) -> dict[str, Any]:
        key = (iso3, year)
        stamp = warehouse_stamp()
        with lock:
            hit = cache.get(key)
            if hit is not None and hit.get("_stamp") == stamp:
                return hit["payload"]
        cached_file = (
            generated_root / f"{iso3}_{year}_{int(stamp)}.json"
            if persist is not None else None
        )
        if cached_file is not None and cached_file.is_file():
            try:
                stored = load_json(cached_file)
            except (OSError, ValueError):
                stored = None
            if isinstance(stored, dict) and stored.get("pages"):
                with lock:
                    if len(cache) >= 8:
                        cache.pop(next(iter(cache)))
                    cache[key] = {"_stamp": stamp, "payload": stored}
                return stored
        try:
            payload = builder(iso3, year)
        except ValidationError as exc:
            raise HTTPException(
                status_code=503,
                detail=(
                    "Le contrat généré pour cette sélection est incomplet ; "
                    "aucune valeur n'a été inventée ni estimée."
                ),
            ) from exc
        except FileNotFoundError as exc:
            raise HTTPException(status_code=503, detail=str(exc)) from exc
        except ValueError as exc:
            raise HTTPException(status_code=404, detail=str(exc)) from exc
        if cached_file is not None:
            _store_generated(cached_file, payload)
        with lock:
            if len(cache) >= 8:
                cache.pop(next(iter(cache)))
            cache[key] = {"_stamp": stamp, "payload": payload}
        return payload

    def resolve_spec(iso3: str | None, year: int | None) -> tuple[dict[str, Any], str]:
        current = load_current()
        current_iso = _current_iso3(current)
        wanted_iso = (iso3 or current_iso).upper()
        wanted_year = year or _current_year(current)
        if wanted_iso == current_iso and wanted_year == _current_year(current):
            payload, source = current, "file"
        else:
            payload, source = generated(wanted_iso, wanted_year), "generated"
        payload = dict(payload)
        payload["survey_years"] = findex_years(wanted_iso)
        return payload, source

    @app.get("/api/health")
    def health() -> dict[str, Any]:
        exists = spec_file.is_file()
        return {
            "status": "ok",
            "spec_path": str(spec_file),
            "spec_loaded": exists,
            "warehouse": str(warehouse),
            "warehouse_present": warehouse.is_file(),
        }

    @app.get("/api/spec")
    def get_spec(
        iso3: str | None = Query(default=None, min_length=3, max_length=3),
        year: int | None = Query(default=None, ge=2000, le=2100),
    ) -> JSONResponse:
        payload, source = resolve_spec(iso3, year)
        return JSONResponse(content=payload, headers={"X-Finova-Source": source})

    @app.get("/api/runs")
    def get_runs(limit: int = Query(default=20, ge=1, le=100)) -> dict[str, Any]:
        runs: list[dict[str, Any]] = []
        if reports.is_dir():
            folders = sorted(
                [path for path in reports.iterdir() if path.is_dir()],
                key=lambda path: path.stat().st_mtime, reverse=True,
            )
            for folder in folders:
                try:
                    summary = load_json(folder / "run.json")
                except (OSError, ValueError):
                    summary = {}
                summary = summary if isinstance(summary, dict) else {}
                runs.append({
                    "run_id": summary.get("run_id", folder.name),
                    "status": summary.get("status"),
                    "objective": summary.get("objective"),
                    "started_at": summary.get("started_at"),
                    "finished_at": summary.get("finished_at"),
                    "errors": (summary.get("errors") or [])[:3],
                    "spec": (folder / "finova_spec.json").is_file(),
                    "route2": summary.get("route2_summary"),
                })
                if len(runs) >= limit:
                    break
        return {"runs": runs, "count": len(runs)}

    @app.post("/api/ask")
    def ask(payload: AskRequest) -> dict[str, Any]:
        spec, source = resolve_spec(payload.iso3, payload.year)
        facts = spec.get("facts") or []
        country = (spec.get("country") or {}).get("name") or "Tunisie"
        result = answer_question(
            payload.question, facts, country=country, year=_current_year(spec),
        )
        result.update({
            "iso3": _current_iso3(spec),
            "year": _current_year(spec),
            "country_name": country,
            "generated_at": spec.get("generated_at"),
            "source": source,
        })
        return result

    dist_dir = Path(dist)
    assets = dist_dir / "assets"
    if assets.is_dir():
        app.mount("/assets", StaticFiles(directory=assets), name="assets")

    @app.get("/", include_in_schema=False)
    def index() -> Any:
        page = dist_dir / "index.html"
        if page.is_file():
            return FileResponse(page)
        return JSONResponse({
            "name": "Finova Dashboard API",
            "docs": "/docs",
            "spec": "/api/spec",
            "ui": "dashboard_app/web non construit (npm run build)",
            "root": str(ROOT),
        })

    if dist_dir.is_dir():
        app.mount("/", StaticFiles(directory=dist_dir, html=True), name="web")

    effective_prewarm = (
        prewarm if prewarm is not None else os.getenv("FINOVA_PREWARM") == "1"
    )
    if effective_prewarm and spec_builder is None and warehouse.is_file():
        def _prewarm() -> None:
            logger = logging.getLogger(__name__)
            try:
                current = load_current()
                published: tuple[str, int] | None = (
                    _current_iso3(current), _current_year(current),
                )
            except HTTPException:
                published = None
            scopes = [
                (code, year) for year in (2024, 2021, 2017) for code in PEERS
                if (code, year) != published
            ]
            for code, year in scopes:
                try:
                    generated(code, year)
                    logger.info("préchauffage terminé : %s %s", code, year)
                except Exception:
                    logger.info(
                        "préchauffage ignoré : %s %s", code, year, exc_info=True,
                    )

        threading.Thread(
            target=_prewarm, name="finova-prewarm", daemon=True,
        ).start()

    return app


app = create_app()


__all__ = ["create_app", "app", "WarehouseSpecBuilder"]
